-- Zone-wide lines, precomputed. Used when nobody is close enough to overhear a local remark.
local shoutLines = {}
for _, line in ipairs(xi.xiLife.chatter.lines) do
    if line.channel == 'shout' then
        table.insert(shoutLines, line)
    end
end

local function livingPNPCs(zone)
    local found = {}

    for _, npc in pairs(zone:getNPCs()) do
        if npc:getLocalVar('xiLife') == 1 and npc:getStatus() ~= xi.status.DISAPPEAR then
            table.insert(found, npc)
        end
    end

    return found
end

local function timeOfDayWord()
    local hour = VanadielHour()

    if hour < 6 then
        return 'the middle of the night'
    elseif hour < 12 then
        return 'morning'
    elseif hour < 17 then
        return 'afternoon'
    elseif hour < 20 then
        return 'evening'
    end

    return 'night'
end

-- Which pool each token draws from. {job2} exists so a line can name two different jobs.
local tokenPool =
{
    zone   = 'zone',
    job    = 'job',
    job2   = 'job',
    item   = 'item',
    price  = 'price',
    number = 'number',
}

local function tokenValue(token, speaker)
    if token == 'name' then
        return speaker.name
    end

    if token == 'time' then
        return timeOfDayWord()
    end

    -- A PNPC in full Artifact is visibly that job, so let it speak as one.
    if token == 'job' and speaker.job then
        return speaker.job
    end

    local pool = xi.xiLife.chatter.tokens[tokenPool[token] or '']
    if pool and #pool > 0 then
        return pool[math.random(#pool)]
    end

    return '{' .. token .. '}'
end

local function fillTokens(text, speaker)
    -- gsub with a function is called once per occurrence, so two {zone} tokens in one line get
    -- independent rolls rather than the same value twice.
    local filled = text:gsub('{(%w+)}', function(token)
        return tokenValue(token, speaker)
    end)

    return filled
end

local scheduleChatter

local function speakOnce(zone, zoneId)
    local state = zoneState[zoneId]
    if not state or not state.active then
        return
    end

    local speakers = livingPNPCs(zone)
    if #speakers == 0 then
        return
    end

    local npc = speakers[math.random(#speakers)]

    -- Work out who could actually overhear this speaker before choosing what it says. Picking the
    -- line first wasted over half of every firing: 'say' lines only carry within SAY_RANGE, and in
    -- a capital the odds of a randomly chosen PNPC standing that close to the player are slim, so
    -- most ticks produced silence. With no one in earshot, only zone-wide lines are eligible.
    local audience = watchingPlayers(zone)
    local nearby   = {}
    for _, player in ipairs(audience) do
        local dx = player:getXPos() - npc:getXPos()
        local dz = player:getZPos() - npc:getZPos()

        if ((dx * dx) + (dz * dz)) <= (SAY_RANGE * SAY_RANGE) then
            table.insert(nearby, player)
        end
    end

    local pool = #nearby > 0 and xi.xiLife.chatter.lines or shoutLines
    if #pool == 0 then
        return
    end

    local line = pool[math.random(#pool)]

    -- The job is only known for PNPCs wearing a full Artifact set; the rest fall back to a random
    -- job in the line, which is fine since nobody can tell what a mixed-gear player is playing.
    local jobId   = npc:getLocalVar('xiLifeJob')
    local speaker =
    {
        name = npc:getName(),
        job  = jobId > 0 and xi.xiLife.chatter.tokens.job[jobId] or nil,
    }

    local text    = fillTokens(line.text, speaker)
    local isShout = line.channel == 'shout'
    local channel = isShout and xi.msg.channel.SHOUT or xi.msg.channel.SAY
    local heard   = isShout and audience or nearby

    for _, player in ipairs(heard) do
        player:printToPlayer(text, channel, speaker.name)
    end
end

-- Each zone's chatter loop carries a generation number. Restarting a zone bumps it, which
-- retires any chain still queued from a previous visit, so afterZoneIn can always start one
-- without risking two running at once.
--
-- Anchoring the loop to a player's action queue means it dies whenever that player's timers are
-- cleared, and the previous guard only started a chain on the transition into active - so once a
-- chain was lost the zone went permanently quiet. Restarting unconditionally fixes that.
scheduleChatter = function(zone, zoneId, generation)
    local state = zoneState[zoneId]
    if not state or not state.active then
        return
    end

    if generation == nil then
        state.chatterGeneration = (state.chatterGeneration or 0) + 1
        generation = state.chatterGeneration
    elseif generation ~= state.chatterGeneration then
        return
    end

    local player = anyPlayerIn(zone)
    if not player then
        return
    end

    local delay = math.random(CHATTER_MIN_DELAY_MS, CHATTER_MAX_DELAY_MS)

    player:timer(delay, function(_)
        -- Re-arm before speaking. If speakOnce throws, the chain has already been queued, so a
        -- single bad line cannot silence the zone for the rest of the session.
        scheduleChatter(zone, zoneId, generation)

        local ok, err = pcall(speakOnce, zone, zoneId)
        if not ok then
            printf('[XI_LIFE] chatter error in %s: %s', zone:getName(), tostring(err))
        end
    end)
end

-----------------------------------
-- Hooks
--
-- InteractionGlobal.afterZoneIn and onZoneOut are called from luautils for every zone, with the
-- zone's own handler passed in as fallbackFn. Call super first and hand its result straight back:
-- these return values are consumed upstream.
-----------------------------------

m:addOverride('InteractionGlobal.afterZoneIn', function(player, fallbackFn)
    local result = super(player, fallbackFn)

    local zone = player:getZone()
    if zone then
        local zoneId = zone:getID()
        local state  = prepareZone(zone, zoneId)

        if state.enabled and player:inMogHouse() then
            -- Walking into a Mog House arrives here, because it is a zone change back into the
            -- same zone. Tear the population down rather than topping it up: the player is still
            -- standing in the street server-side, so anything spawned would be pushed to their
            -- client and parade through the room.
            state.active = false
            despawnAll(zone, zoneId)
        elseif state.enabled then
            state.active = true
            topUpPopulation(zone, zoneId)

            -- Always restart. The generation counter retires whatever was queued before, so this
            -- cannot double the rate, and it recovers a chain that died with a player's timers.
            scheduleChatter(zone, zoneId)
            scheduleEncounters(zone, zoneId)
        end
    end

    return result
end)

m:addOverride('InteractionGlobal.onZoneOut', function(player, fallbackFn)
    local result = super(player, fallbackFn)

    local zone = player:getZone()
    if zone then
        local zoneId = zone:getID()
        local state  = zoneState[zoneId]

        -- Only tear down once the last player is gone. getPlayers still includes the player who is
        -- on their way out at this point, so one remaining means the zone is about to be empty.
        if state and state.enabled and #zone:getPlayers() <= 1 then
            state.active = false
            despawnAll(zone, zoneId)
        end
    end

    return result
end)

return m
