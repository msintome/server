-----------------------------------
-- XI_LIFE: PlayerNPC city population
--
-- Populates every city zone a player walks into with dynamic NPCs that look and move like other
-- players: they arrive somewhere, loiter, walk on, and eventually leave through a zone line or a
-- home point crystal.
--
-- Hooks in through InteractionGlobal rather than per-zone scripts. luautils calls
-- InteractionGlobal.afterZoneIn and InteractionGlobal.onZoneOut unconditionally for every zone,
-- passing the zone's own handler in as a fallback, so overriding those two reaches all 250-odd
-- zones without editing a single Zone.lua.
--
-- Points of interest come from modules/custom/lua/xi_life_pois.lua, which is generated by
-- tools/xi_life/generate_pois.py out of npc_list, zonelines and the zone scripts.
-----------------------------------
require('modules/module_utils')
require('scripts/globals/interaction/interaction_global')
require('modules/custom/lua/xi_life_appearance')
require('modules/custom/lua/xi_life_pois')
require('modules/custom/lua/xi_life_chatter')

-- Hand-picked points added in game with !addnpcpoi. Optional: the file only exists once the
-- command has been used at least once, so this must not be a hard require. pcall rather than
-- utils.prequire, which lives in scripts/utils and may not be loaded this early.
pcall(require, 'modules/custom/lua/xi_life_custom_pois')
